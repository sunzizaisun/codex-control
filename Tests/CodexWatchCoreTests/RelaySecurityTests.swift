@testable import CodexWatchCore

private let relayFixtureSecret = String(repeating: "fixture-only-", count: 4)

@Test func relayAuthenticationCannotDecryptOrForgeDevicePackets() throws {
    let credentials = try RelayCredentials.migrating(secret: relayFixtureSecret, roomID: "qa-room")
    let cipher = RelayPacketCipher(roomID: "qa-room", credentials: credentials)
    let envelope = BridgeEnvelope(sentAt: Date(timeIntervalSince1970: 1000), kind: .taskCommand, senderDeviceID: "watch", message: "原文：海狸-428🍁")
    let packet = try cipher.seal(envelope, destination: "mac")
    #expect(try cipher.open(packet, destination: "mac") == envelope)
    let serverKey = try #require(Data(base64Encoded: credentials.authToken))
    #expect(serverKey != credentials.encryptionKey)
    let compromised = try RelayCredentials(authToken: credentials.authToken, encryptionKey: Data(serverKey.map { $0 ^ 0x01 }))
    let attacker = RelayPacketCipher(roomID: "qa-room", credentials: compromised)
    #expect(throws: (any Error).self) { try attacker.open(packet, destination: "mac") }
    // Even bypassing the key-ID check and using the server token directly as
    // an AES key fails the GCM tag. This tests the original vulnerability.
    let combined = try #require(Data(base64Encoded: packet.sealed))
    let aad = Data(["codex-control/relay", "2", packet.keyID, "qa-room", "mac", packet.id,
                    String(packet.sentAt), String(packet.expiresAt)].joined(separator: "\n").utf8)
    #expect(throws: (any Error).self) {
        try AES.GCM.open(AES.GCM.SealedBox(combined: combined), using: SymmetricKey(data: serverKey), authenticating: aad)
    }
    let legacyKey = Data(SHA256.hash(data: Data(relayFixtureSecret.utf8)))
    #expect(legacyKey != credentials.encryptionKey)
}

@Test func relayAuthenticatedMetadataRejectsAllRoutingAndDeadlineChanges() throws {
    let credentials = try RelayCredentials.migrating(secret: relayFixtureSecret, roomID: "qa-room")
    let cipher = RelayPacketCipher(roomID: "qa-room", credentials: credentials)
    let packet = try cipher.seal(BridgeEnvelope(kind: .approvalDecision, senderDeviceID: "watch"), destination: "mac")
    var mutations: [RelaySealedPacket] = []
    var changed = packet; changed.version = 1; mutations.append(changed)
    changed = packet; changed.keyID = String(repeating: "0", count: 32); mutations.append(changed)
    changed = packet; changed.id = "different-id"; mutations.append(changed)
    changed = packet; changed.sentAt += 1; mutations.append(changed)
    changed = packet; changed.expiresAt += 1; mutations.append(changed)
    changed = packet; changed.destination = "phone"; mutations.append(changed)
    for mutation in mutations {
        #expect(throws: (any Error).self) { try cipher.open(mutation, destination: "mac") }
    }
    #expect(throws: (any Error).self) { try cipher.open(packet, destination: "phone") }
    let otherRoom = RelayPacketCipher(roomID: "other-room", credentials: credentials)
    #expect(throws: (any Error).self) { try otherRoom.open(packet, destination: "mac") }
}

@Test func relayV2RejectsLegacyPacketsInsteadOfFallingBack() throws {
    let legacy = Data(#"{"id":"old","sentAt":1000,"expiresAt":2000,"sealed":"YQ=="}"#.utf8)
    #expect(throws: (any Error).self) { try JSONDecoder().decode(RelaySealedPacket.self, from: legacy) }
    let same = Data(repeating: 42, count: 32)
    #expect(throws: (any Error).self) { try RelayCredentials(authToken: same.base64EncodedString(), encryptionKey: same) }
    #expect(throws: (any Error).self) { try RelayCredentials.migrating(secret: "short", roomID: "qa-room") }
}

@Test func migratedRelayKeysAreRepeatableAcrossDevicesAndRoomScoped() throws {
    let phone = try RelayCredentials.migrating(secret: relayFixtureSecret, roomID: "qa-room")
    let watch = try RelayCredentials.migrating(secret: relayFixtureSecret, roomID: "qa-room")
    let other = try RelayCredentials.migrating(secret: relayFixtureSecret, roomID: "other-room")
    #expect(phone.authToken == watch.authToken)
    #expect(phone.encryptionKey == watch.encryptionKey)
    #expect(phone.keyID == watch.keyID)
    #expect(phone.authToken != other.authToken)
    #expect(phone.encryptionKey != other.encryptionKey)
    let fresh = try RelayCredentials.generate()
    #expect(fresh.authToken != phone.authToken)
    #expect(fresh.encryptionKey != phone.encryptionKey)
    // Cross-language fixture generated by Node's RFC 5869 HKDF, matching the
    // upload tool. Only hashes of public fixture keys are embedded here.
    let authData = try #require(Data(base64Encoded: phone.authToken))
    #expect(SHA256.hash(data: authData).map { String(format: "%02x", $0) }.joined() == "86b75171167c5cfe802e2d1fdb9e7b13094b104c1dacfe3ead81854a28f0feae")
    #expect(SHA256.hash(data: phone.encryptionKey).map { String(format: "%02x", $0) }.joined() == "1337171ba216bb902c7c51fec13d887a66db77423e2d96936e9c76bf457f3bf6")
}

@Test func invalidWireDateThrowsInsteadOfTrappingTheBridge() {
    for interval in [Double.infinity, Double.nan, 1e100] {
        let envelope = BridgeEnvelope(sentAt: Date(timeIntervalSince1970: interval), kind: .taskCommand, senderDeviceID: "fixture")
        #expect(throws: (any Error).self) { try CodexWatchCoding.makeEncoder().encode(envelope) }
    }
}

